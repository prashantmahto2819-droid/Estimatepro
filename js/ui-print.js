/* Estimate Pro — Print preview for estimates and CAD drawings.
   Opens a print-friendly page in a new tab / popup. */
(function () {
  "use strict";
  var EP = window.EP, S = EP.S, U = EP.ui, esc = U.esc;

  /* ---------- estimate print ---------- */
  function fmtNum(n) { if (n == null || isNaN(n)) return ""; return Number(n).toLocaleString("en-IN", { maximumFractionDigits: 3 }); }
  function fmtAmt(n) { if (n == null || isNaN(n)) return ""; return "₹ " + Number(n).toLocaleString("en-IN", { maximumFractionDigits: 2, minimumFractionDigits: 2 }); }

  U.printEstimate = function (est) {
    if (!est || !est.doc) { U.toast("Open an estimate first · पहले एस्टिमेट खोलें"); return; }
    var d = est.doc, items = d.items || d.rows || [], gst = +d.gst || 0;
    var name = est.name || d.name || "Untitled Estimate";
    var total = 0;

    var rows = items.map(function (it, i) {
      var qty = it.qty != null ? +it.qty : ((it.no || 1) * (it.l || 1) * (it.b || 1) * (it.d || 1));
      var rate = +it.rate || 0, amt = qty * rate;
      total += amt;
      return "<tr><td>" + (i + 1) + "</td><td class='l'>" + esc(it.desc || it.description || it.name || "") + "</td>" +
        "<td>" + (it.no || "") + "</td><td>" + (it.l || "") + "</td><td>" + (it.b || "") + "</td><td>" + (it.d || it.h || "") + "</td>" +
        "<td>" + fmtNum(qty) + "</td><td>" + esc(it.unit || "") + "</td><td class='r'>" + fmtNum(rate) + "</td><td class='r'>" + fmtAmt(amt) + "</td></tr>";
    });

    var gstAmt = total * gst / 100, grand = total + gstAmt;

    var html = "<!doctype html><html><head><meta charset='utf-8'><title>" + esc(name) + "</title><style>" +
      "body{font-family:system-ui,'Segoe UI',Roboto,sans-serif;margin:0;color:#111;font-size:12px}" +
      ".pg{padding:12mm 10mm;max-width:210mm;margin:0 auto}" +
      "h1{font-size:16px;margin:0 0 2px}h2{font-size:13px;margin:0 0 8px;font-weight:400;color:#555}" +
      "table{width:100%;border-collapse:collapse;margin-top:6px}" +
      "th,td{border:1px solid #999;padding:3px 6px;font-size:11px}" +
      "th{background:#e8e8e8;font-weight:600;text-align:center}" +
      ".l{text-align:left}.r{text-align:right}" +
      ".total td{font-weight:700;background:#f5f5f5}" +
      ".hdr{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #333;padding-bottom:6px;margin-bottom:8px}" +
      ".noprint{margin-bottom:12px}" +
      "@media print{.noprint{display:none}@page{size:A4 landscape;margin:8mm}}" +
      "</style></head><body><div class='pg'>" +
      "<div class='noprint'><button onclick='print()'>🖨 Print / Save as PDF</button></div>" +
      "<div class='hdr'><div><h1>" + esc(name) + "</h1><h2>" + esc(d.client || d.project || "") + (d.location ? " · " + esc(d.location) : "") + "</h2></div><div style='text-align:right;font-size:11px'>Date: " + new Date().toLocaleDateString("en-IN") + "<br>" + esc((S.me && S.me.name) || "") + "</div></div>" +
      "<table><thead><tr><th>Sr</th><th>Description of work</th><th>No</th><th>L</th><th>B</th><th>D/H</th><th>Qty</th><th>Unit</th><th>Rate (₹)</th><th>Amount (₹)</th></tr></thead><tbody>" +
      rows.join("") +
      "<tr class='total'><td colspan='9' class='r'>Sub Total</td><td class='r'>" + fmtAmt(total) + "</td></tr>" +
      (gst ? "<tr class='total'><td colspan='9' class='r'>GST @ " + gst + "%</td><td class='r'>" + fmtAmt(gstAmt) + "</td></tr>" : "") +
      "<tr class='total'><td colspan='9' class='r'>Grand Total</td><td class='r'>" + fmtAmt(grand) + "</td></tr>" +
      "</tbody></table>" +
      "<div style='margin-top:20mm;display:flex;justify-content:space-between'><div style='border-top:1px solid #333;width:45%;text-align:center;padding-top:4px'>Prepared by</div><div style='border-top:1px solid #333;width:45%;text-align:center;padding-top:4px'>Approved by</div></div>" +
      "<p style='margin-top:8px;font-size:9px;color:#999;text-align:center'>Generated by Estimate Pro · " + new Date().toLocaleString("en-IN") + "</p>" +
      "</div></body></html>";

    var w = window.open("", "_blank");
    if (!w) { U.toast("Allow pop-ups for print preview · पॉप-अप की अनुमति दें"); return; }
    w.document.open(); w.document.write(html); w.document.close();
  };

  /* ---------- abstract sheet (MPPWD format) ---------- */
  U.printAbstract = function (est) {
    if (!est || !est.doc) { U.toast("Open an estimate first"); return; }
    var d = est.doc, items = d.items || d.rows || [], name = est.name || "Untitled";
    var gst = +d.gst || 0, total = 0;

    /* group by chapter / section */
    var sections = {}, order = [];
    items.forEach(function (it) {
      var sec = it.section || it.chapter || "General";
      if (!sections[sec]) { sections[sec] = []; order.push(sec); }
      sections[sec].push(it);
    });

    var body = "";
    order.forEach(function (sec) {
      var rows = sections[sec], secTotal = 0;
      body += "<tr class='total'><td colspan='5' class='l'><b>" + esc(sec) + "</b></td></tr>";
      rows.forEach(function (it, i) {
        var qty = it.qty != null ? +it.qty : ((it.no || 1) * (it.l || 1) * (it.b || 1) * (it.d || 1));
        var rate = +it.rate || 0, amt = qty * rate;
        secTotal += amt; total += amt;
        body += "<tr><td>" + (i + 1) + "</td><td class='l'>" + esc(it.desc || it.description || "") + "</td><td>" + fmtNum(qty) + " " + esc(it.unit || "") + "</td><td class='r'>" + fmtNum(rate) + "</td><td class='r'>" + fmtAmt(amt) + "</td></tr>";
      });
      body += "<tr class='total'><td colspan='4' class='r'>" + esc(sec) + " total</td><td class='r'>" + fmtAmt(secTotal) + "</td></tr>";
    });

    var gstAmt = total * gst / 100;

    var html = "<!doctype html><html><head><meta charset='utf-8'><title>Abstract — " + esc(name) + "</title><style>" +
      "body{font-family:system-ui,sans-serif;margin:0;color:#111;font-size:12px}" +
      ".pg{padding:12mm;max-width:210mm;margin:0 auto}" +
      "table{width:100%;border-collapse:collapse}th,td{border:1px solid #aaa;padding:3px 6px;font-size:11px}" +
      "th{background:#e8e8e8;font-weight:600}.l{text-align:left}.r{text-align:right}.total td{font-weight:600;background:#f8f8f8}" +
      ".noprint{margin-bottom:10px}@media print{.noprint{display:none}@page{size:A4;margin:10mm}}" +
      "</style></head><body><div class='pg'>" +
      "<div class='noprint'><button onclick='print()'>🖨 Print</button></div>" +
      "<h1 style='font-size:15px;margin:0 0 2px'>Abstract of Cost</h1>" +
      "<h2 style='font-size:12px;margin:0 0 10px;color:#555'>" + esc(name) + "</h2>" +
      "<table><thead><tr><th>Sr</th><th>Item</th><th>Qty</th><th>Rate (₹)</th><th>Amount (₹)</th></tr></thead><tbody>" +
      body +
      "<tr class='total'><td colspan='4' class='r'>Net Total</td><td class='r'>" + fmtAmt(total) + "</td></tr>" +
      (gst ? "<tr class='total'><td colspan='4' class='r'>GST @ " + gst + "%</td><td class='r'>" + fmtAmt(gstAmt) + "</td></tr><tr class='total'><td colspan='4' class='r'>Grand Total</td><td class='r'>" + fmtAmt(total + gstAmt) + "</td></tr>" : "") +
      "</tbody></table>" +
      "<p style='margin-top:15mm;font-size:9px;color:#999;text-align:center'>Estimate Pro · " + new Date().toLocaleString("en-IN") + "</p>" +
      "</div></body></html>";

    var w = window.open("", "_blank"); if (!w) { U.toast("Allow pop-ups"); return; }
    w.document.open(); w.document.write(html); w.document.close();
  };

  /* ---------- CAD drawing print ---------- */
  U.printDrawing = function () {
    if (!S.cad || !S.cad.v3) { U.toast("Open a 3D view first"); return; }
    var v = S.cad.v3, png = v.png();
    var title = (S.cad.doc && S.cad.doc.name) || "CAD Drawing";

    var html = "<!doctype html><html><head><meta charset='utf-8'><title>" + esc(title) + "</title><style>" +
      "body{font-family:system-ui,sans-serif;margin:0;text-align:center}" +
      "img{max-width:100%;max-height:85vh;margin:12px auto}" +
      ".noprint{margin:12px}@media print{.noprint{display:none}@page{size:A4 landscape;margin:5mm}}" +
      "</style></head><body>" +
      "<div class='noprint'><button onclick='print()'>🖨 Print</button></div>" +
      "<h3 style='margin:8px 0 0;font-size:14px'>" + esc(title) + "</h3>" +
      "<img src='" + png + "' alt='Drawing'>" +
      "<p style='font-size:9px;color:#999'>Estimate Pro · " + new Date().toLocaleString("en-IN") + "</p>" +
      "</body></html>";

    var w = window.open("", "_blank"); if (!w) { U.toast("Allow pop-ups"); return; }
    w.document.open(); w.document.write(html); w.document.close();
  };

  /* toolbar button */
  U.printButton = function () {
    return '<button type="button" class="btn ghost sm" id="est-print" title="Print preview · प्रिंट करें">🖨 <span class="hide-sm">Print</span></button>';
  };

  document.addEventListener("click", function (ev) {
    var t = ev.target.closest && ev.target.closest("button");
    if (!t) return;
    if (t.id === "est-print") {
      if (S.est && S.est.open) U.printEstimate(S.est.open);
      else if (S.cad && S.cad.v3) U.printDrawing();
      else U.toast("Nothing to print — open an estimate or drawing · प्रिंट करने के लिए कुछ खोलें");
    }
    if (t.id === "est-abstract") U.printAbstract(S.est && S.est.open);
  });
})();
